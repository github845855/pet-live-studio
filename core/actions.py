"""Action labels shown to the LLM, plus the clip catalog used by the stage.

The LLM only ever emits the 13 stable Chinese labels below. Each label is
mapped to one concrete webm clip through ``catalog.json`` (generated by
``tools/build_action_catalog.py``), so we can grow the clip library without
touching the prompt.
"""

import json
from pathlib import Path

ACTION_LABELS = {
    "idle": "待机",
    "welcome_wave": "挥手欢迎",
    "happy_jump": "开心跳跃",
    "shy": "害羞",
    "grumpy": "傲娇生气",
    "laugh": "开心大笑",
    "thinking": "思考",
    "busy": "忙碌",
    "celebrate": "雀跃庆祝",
    "bored": "无聊",
    "surprised": "吓一跳",
    "gift": "拆礼物",
    "sleepy": "打瞌睡",
}

ACTION_IDS_BY_LABEL = {label: action for action, label in ACTION_LABELS.items()}

CATALOG_FILE = Path(__file__).resolve().parent.parent / "web" / "actions" / "catalog.json"


def load_catalog(path=None):
    """Read the clip catalog; a missing or broken file degrades to "no clips"."""
    try:
        raw = json.loads(Path(path or CATALOG_FILE).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        raw = {}
    if not isinstance(raw, dict):
        raw = {}
    clips = raw.get("clips")
    aliases = raw.get("aliases")
    return {
        "clips": clips if isinstance(clips, dict) else {},
        "aliases": aliases if isinstance(aliases, dict) else {},
        "categories": raw.get("categories") if isinstance(raw.get("categories"), list) else [],
        "events": raw.get("events") if isinstance(raw.get("events"), dict) else {},
        "weights": raw.get("weights") if isinstance(raw.get("weights"), dict) else {},
        "clip": raw.get("clip") if isinstance(raw.get("clip"), dict) else {},
    }


CATALOG = load_catalog()
CLIP_FILES = {
    name: str(info.get("file") or f"{name}.webm")
    for name, info in CATALOG["clips"].items()
    if isinstance(info, dict)
}


def stage_actions_payload():
    """Compact catalog for the stage: names, durations, aliases, weights."""
    clips = {}
    for name, info in CATALOG["clips"].items():
        if not isinstance(info, dict):
            continue
        try:
            duration = round(float(info.get("duration") or 10.0), 2)
        except (TypeError, ValueError):
            duration = 10.0
        clips[name] = duration
    return {
        "clip": CATALOG["clip"],
        "clips": clips,
        "aliases": {
            action: CATALOG["aliases"].get(action, "")
            for action in ACTION_LABELS
        },
        "categories": CATALOG["categories"],
        "events": CATALOG["events"],
        "weights": CATALOG["weights"],
    }

